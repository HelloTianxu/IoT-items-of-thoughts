import assert from 'node:assert/strict';
import { mkdtempSync, realpathSync, readFileSync, symlinkSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { SessionMemory } from './lib/session-memory.mjs';
const root=realpathSync(mkdtempSync(join(tmpdir(),'iot-memory-')));
const memory=new SessionMemory({root});
const summary=memory.execute('a',{action:'write',id:'summary',title:'当前目标',content:'完成会话归档'});
assert.equal(summary.revision,1);
assert.equal(memory.execute('b',{action:'read'}).found,false);
assert.throws(()=>memory.execute('a',{action:'write',id:'summary',title:'x',content:'x'}),{code:'MEMORY_EXISTS'});
assert.throws(()=>memory.execute('a',{action:'update',id:'summary',expectedRevision:0,content:'x'}),{code:'MEMORY_CONFLICT'});
const update=memory.execute('a',{action:'update',id:'summary',expectedRevision:1,content:'已验证归档，继续记忆接口'});
assert.equal(update.revision,2);
const note=memory.execute('a',{action:'write',title:'失败路线',content:'不要将未验证当作失败',sources:[{turn:2,seq:8}]});
assert.equal(memory.execute('a',{action:'search',query:'未验证'}).total,1);
const rendered=readFileSync(join(note.directory,'memory.md'),'utf8');
assert.match(rendered,/revision 2/);assert.match(rendered,/UTC/);assert.match(rendered,/#seq-8/);assert.match(rendered,/会话目录/);
assert.equal(memory.execute('a',{action:'list',limit:1}).items.length,1);
const archive=memory.archive;archive.recordEvent('a',{seq:0,type:'turn/start',data:{turn:0}});
const before=readFileSync(archive.inspect('a').files.events,'utf8');
assert.equal(memory.execute('a',{action:'delete',id:note.id,expectedRevision:1}).deleted,true);
assert.equal(memory.execute('a',{action:'read',id:note.id}).found,false);
assert.equal(memory.execute('a',{action:'search',query:'未验证'}).total,0);
assert.equal(readFileSync(archive.inspect('a').files.events,'utf8'),before);
assert.equal(new SessionMemory({root}).execute('a',{action:'read'}).memory.revision,2);
assert.throws(()=>memory.execute('a',{action:'write',id:'../x',title:'x',content:'x'}),{code:'MEMORY_ID'});
assert.throws(()=>memory.execute('a',{action:'write',title:'x',content:'x'.repeat(32001)}),{code:'MEMORY_CONTENT'});
memory.execute('link',{action:'read'});
symlinkSync(join(archive.inspect('a').directory,'memories.json'),join(archive.inspect('link').directory,'memories.json'));
assert.throws(()=>memory.execute('link',{action:'read'}),{code:'ARCHIVE_UNSAFE_PATH'});
console.log('PASS session memory: CRUD, summary, revisions, search, restart, isolation, logical delete, unsafe paths');
