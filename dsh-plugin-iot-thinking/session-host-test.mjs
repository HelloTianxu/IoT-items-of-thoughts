// Installed host integration: real session events, tool schemas and skill registry; no model/network/profile writes.
import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { mkdtempSync,realpathSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join,resolve,dirname } from 'node:path';
const require=createRequire(join(process.env.DSH_INSTALL_DIR,'package.json'));
const {Context,Service}=await import(require.resolve('@deepseek-ai/cordis'));
const {default:Sessions}=await import(require.resolve('@deepseek-ai/dsh-session'));
const {default:Skills}=await import(require.resolve('@deepseek-ai/dsh-skill'));
const {default:Tools}=await import(require.resolve('@deepseek-ai/dsh-tools'));
const {default:SystemPrompt}=await import(require.resolve('@deepseek-ai/dsh-system-prompt'));
const Native=await import(require.resolve('@deepseek-ai/dsh-tool-executor-native'));
const Llm=await import(require.resolve('@deepseek-ai/dsh-llm'));
const rootDir=realpathSync(mkdtempSync(join(tmpdir(),'iot-session-host-')));
process.env.IOT_THINKING_DATA_DIR=rootDir;
process.env.IOT_THINKING_CONFIG_PATH=join(rootDir,'config.json');
process.env.IOT_DSH_SEAM_ANCHORS=resolve(dirname(require.resolve('@deepseek-ai/dsh-llm')),'../../..');
const plugin=await import('./index.mjs');
class FakeLlm extends Service{constructor(ctx){super(ctx,'llm');}stream(){throw new Error('No model calls allowed');}}
const ctx=new Context();
await ctx.plugin(Sessions);await ctx.plugin(Skills);await ctx.plugin(Tools);await ctx.plugin(SystemPrompt);await ctx.plugin(Native);await ctx.plugin(FakeLlm);
const fiber=await ctx.plugin(plugin,{webApi:false,command:false});
await new Promise(r=>setImmediate(r));
const skill=await ctx.skills.get('iot-session-memory');
// Actual session/event dispatch, not only a hand-written fake event feed.
const realSession=ctx.sessions.create('iot-real-event-fixture');
realSession.append('turn/start',{turn:1});
realSession.append('user/message',Llm.createUserMessage({content:[{type:'text',text:'actual host durable user'}],source:{kind:'user'}}),{surfaceOp:'append'});
realSession.append('turn/end',{turn:1,reason:{kind:'completed'}});
await ctx.sessions.flush(realSession);
const {SessionArchive}=await import('./lib/session-archive.mjs');
assert.match(new SessionArchive({root:join(rootDir,'sessions')}).read(realSession.id,{turn:1}),/actual host durable user/);
assert.ok(skill);assert.match(skill.content,/iot_session_log/);
const assembly=await ctx.systemPrompt.assemble();
for(const name of ['iot_session_log','iot_session_memory'])assert.ok(assembly.tools.some(t=>t.name===name),`${name} visible in native schema`);
const {registerSessionMemory}=await import('./lib/session-memory-tools.mjs');
const {createArchiveRuntime}=await import('./lib/archive-runtime.mjs');
const hooks=new Map(), defs=new Map();
const fake={on:(n,f)=>hooks.set(n,f),effect:f=>f(),get:()=>undefined,inject:(deps,fn)=>{if(deps.includes('tools'))return fn({tools:{register:def=>{defs.set(def.name,def);return()=>{};}}});}};
const runtime=createArchiveRuntime(fake,{getConfig:()=>({sessionLog:true})});
registerSessionMemory(fake,{defineTool:x=>x,runtime,getConfig:()=>({sessionMemory:true})});
const sid='test-session', exec={agent:{session:{id:sid}},signal:new AbortController().signal};
const event=(seq,type,data)=>({seq,type,time:Date.now(),data});
for(const e of [event(0,'turn/start',{turn:1}),event(1,'user/message',{role:'user',source:{kind:'user'},content:[{type:'text',text:'真实回忆测试 secret clue'}]}),event(2,'turn/end',{turn:1,reason:{kind:'completed'}})])hooks.get('session/event')({id:sid},e);
await runtime.settled();
const mem=defs.get('iot_session_memory'),log=defs.get('iot_session_log');
const emptyId=await mem.execute({action:'write',id:'',title:'empty id regression',content:'auto UUID'},exec);
assert.equal(emptyId.ok,true,JSON.stringify(emptyId));assert.match(emptyId.id,/^[0-9a-f-]{36}$/);
const partialUpdate=await mem.execute({action:'update',id:emptyId.id,expectedRevision:1,title:'',content:'updated'},exec);
assert.equal(partialUpdate.ok,true);assert.equal((await mem.execute({action:'read',id:emptyId.id},exec)).memory.title,'empty id regression');
const write=await mem.execute({action:'write',id:'summary',title:'进度',content:'已完成原始归档',sources:[{turn:1,seq:1}]},exec);assert.equal(write.ok,true,JSON.stringify(write));
assert.equal((await mem.execute({action:'read'},exec)).memory.content,'已完成原始归档');
assert.equal((await mem.execute({action:'read'},{agent:{session:{id:'other'}}})).found,false);
assert.equal((await mem.execute({action:'write',title:'坏来源',content:'x',sources:[{turn:99}]},exec)).ok,false);
assert.match((await log.execute({action:'read',turn:1,limit:300},exec)).text,/secret clue/);
assert.ok((await log.execute({action:'search',query:'secret clue'},exec)).matches.every(x=>x.turn===1));
assert.equal((await log.execute({action:'read',turn:1},{})).ok,false);
assert.equal((await mem.execute({action:'delete',id:'summary',expectedRevision:0},exec)).code,'MEMORY_CONFLICT');
assert.equal((await mem.execute({action:'delete',id:'summary',expectedRevision:1},exec)).ok,true);
assert.equal((await log.execute({action:'list'},exec)).total,1);
await fiber.dispose();await ctx.fiber.dispose();
console.log('PASS installed session host: real tools+skill catalog, source validation, CRUD/log fallback and session isolation');
